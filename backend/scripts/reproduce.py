"""Rebuild every table of docs/reports/paper_analysis.md from the saved results, with one command.

Each step re-runs an evaluation script on its cached inputs (model outputs, rewrites, translations,
judge labels are all cached under data/reports/ and benchmark/), so nothing is sent to a model:
the API keys are replaced by an invalid placeholder for the run, and a step whose cache is
incomplete fails loudly instead of calling a model or spending money. Steps that need data which is
not in the repository (downloaded judgments, the BPRD PDF, model checkpoints) are skipped and listed.

Output: docs/reports/reproduced.md - every step's command, status, and output (the tables).

Usage (from the repo root):
    python backend/scripts/reproduce.py              # all steps
    python backend/scripts/reproduce.py --only hindi injection
"""

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PY = sys.executable
OUT = ROOT / "docs" / "reports" / "reproduced.md"
DR = ROOT / "data" / "reports"


def summary(path: str) -> str:
    """A saved summary file, printed (for runs that cannot be repeated without a model)."""
    p = ROOT / path
    return json.dumps(json.loads(p.read_text(encoding="utf-8")), indent=1)


# (id, paper section, what, command or callable, files it needs)
STEPS = [
    ("headline", "§0-1", "LegalGPT vs each model alone: paired McNemar tests",
     [PY, "backend/scripts/paired_tests.py"], ["data/reports/bench"]),
    ("classifier", "§7b", "Sentence roles: InLegalBERT ablation and ensemble (CV, McNemar, bootstrap)",
     [PY, "backend/scripts/rrl_round2_report.py"], ["data/models/rrl_cv"]),
    ("hindi", "§9", "Hindi retrieval: en / hi-raw / hi-rewrite / hi-translate",
     [PY, "backend/scripts/eval_hindi.py", "--translate-model", "gemini:gemini-3.5-flash-lite"],
     ["benchmark/hindi/questions_hi.jsonl", "data/reports/hindi"]),
    ("hindi-answers", "§9", "Hindi end to end (saved run; repeating it needs a model)",
     lambda: summary("data/reports/hindi/summary_answers_groq_openai_gpt-oss-120b.json"), ["data/reports/hindi"]),
    ("injection", "§9", "Prompt injection, before / after the defences (saved runs; repeating them needs a model)",
     lambda: "\n".join(f"{n}:\n{summary(f'data/reports/injection/{n}-summary.json')}"
                       for n in ("baseline-gemini-3.5-flash-lite", "hardened-gemini-3.5-flash-lite")), ["data/reports/injection"]),
    ("guard-patterns", "§9", "Output guard, worst case: patterns only",
     [PY, "backend/scripts/eval_guard_worst_case.py", "--patterns-only"], ["data/reports/injection"]),
    ("guard", "§9", "Output guard, worst case: patterns + verdict classifier",
     [PY, "backend/scripts/eval_guard_worst_case.py"], ["data/reports/injection"]),
    ("verdict-classifier", "§9", "Verdict classifier: train (gpt-oss) / held-out test (qwen)",
     [PY, "backend/scripts/eval_verdict_guard.py"], ["benchmark/verdict_guard"]),
    ("faithfulness", "§9", "Judgment-citation faithfulness: two judges, agreement, case names",
     [PY, "backend/scripts/eval_citation_faithfulness.py", "--cached-answers", "--model", "gemini:gemini-3.5-flash-lite",
      "--judges", "groq:openai/gpt-oss-120b", "groq:qwen/qwen3.8-27b"], ["data/reports/faithfulness"]),
    ("case-analysis", "§9", "Case analysis on 120 SC judgments (cached analyses)",
     [PY, "backend/scripts/eval_case_analysis.py", "--n", "120"], ["data/reports/case_eval", "data/judgment_library"]),
    ("bns", "§4", "IPC -> BNS map from the BPRD table",
     [PY, "backend/scripts/build_bns_map.py", "--pdf", "data/bns/comparison_summary_BNS_to_IPC.pdf"],
     ["data/bns/comparison_summary_BNS_to_IPC.pdf"]),
    ("blind-samples", "Label", "InLegalBERT on blind samples",
     [PY, "backend/scripts/eval_blind_samples.py"], []),
]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", nargs="*", help="step ids: " + " ".join(s[0] for s in STEPS))
    ap.add_argument("--timeout", type=int, default=1800)
    args = ap.parse_args()
    env = {**os.environ, "PYTHONIOENCODING": "utf-8"}
    for var in ("GROQ_API_KEY", "GEMINI_API_KEY", "OPENAI_API_KEY", "OPENROUTER_API_KEY"):
        env[var] = "offline-reproduce"  # an invalid key: a cache miss fails instead of calling a model
    lines = ["# Reproduced results", "",
             f"Generated by `backend/scripts/reproduce.py` on {time.strftime('%Y-%m-%d %H:%M')}, from cached results only "
             "(no model calls). Section numbers refer to docs/reports/paper_analysis.md.", ""]
    status = []
    for sid, section, what, cmd, needs in STEPS:
        if args.only and sid not in args.only:
            continue
        missing = [n for n in needs if not (ROOT / n).exists()]
        lines += [f"## {what} ({section})", ""]
        if missing:
            lines += [f"Skipped: needs {', '.join(missing)} (not in the repository).", ""]
            status.append((sid, "skipped"))
            print(f"[skip] {sid}: needs {missing}", flush=True)
            continue
        t0 = time.time()
        if callable(cmd):
            try:
                out, ok = cmd(), True
            except Exception as e:
                out, ok = f"{type(e).__name__}: {e}", False
            shown = "(saved summary)"
        else:
            r = subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True, encoding="utf-8",
                               errors="replace", timeout=args.timeout)
            noise = ("WARNING", "Loading weights", "Warning: You are sending", "it/s]")
            out = "\n".join(ln for ln in (r.stdout + r.stderr).splitlines() if not any(n in ln for n in noise))
            ok = r.returncode == 0
            shown = "`" + " ".join(Path(c).name if i == 0 else c for i, c in enumerate(cmd)) + "`"
        status.append((sid, "ok" if ok else "FAILED"))
        print(f"[{'ok' if ok else 'FAILED'}] {sid} ({time.time() - t0:.0f}s)", flush=True)
        lines += [f"Command: {shown} · {'ok' if ok else '**failed**'}", "", "```", out.strip()[-12000:], "```", ""]
    lines[4:4] = ["| step | status |", "|---|---|", *[f"| {s} | {st} |" for s, st in status], ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0 if all(st != "FAILED" for _, st in status) else 1


if __name__ == "__main__":
    sys.exit(main())
