"""Combine the baseline and counterfactual results into docs/reports/benchmark_results.md.

Reads the cached answers (data/reports/bench/), rescores them with app/benchmark/metrics.py, and
writes rates with Wilson 95% confidence intervals and the sample sizes, so small samples are not
over-read. Re-run after more answers have been collected (the runners resume across days).

Usage (from the repo root):
    python backend/scripts/report_experiments.py
"""

import json
import math
import subprocess
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.config import REPO_ROOT  # noqa: E402

BENCH = REPO_ROOT / "data" / "reports" / "bench"


def wilson(k: int, n: int) -> str:
    if n == 0:
        return "-"
    z, p = 1.96, k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return f"{100 * p:.0f}% [{100 * max(0, c - h):.0f}–{100 * min(1, c + h):.0f}] (n={n})"


def main() -> int:
    py = sys.executable
    for script in ("run_baselines.py", "run_counterfactual.py"):
        subprocess.run([py, str(REPO_ROOT / "backend" / "scripts" / script), "score"], check=True, capture_output=True)
    base = json.loads((BENCH / "baselines" / "summary.json").read_text(encoding="utf-8"))
    cf = json.loads((BENCH / "counterfactual" / "summary.json").read_text(encoding="utf-8"))
    md = [f"# Benchmark results ({date.today().isoformat()})", "",
          "Generated by `backend/scripts/report_experiments.py` from the cached runs. Percentages carry Wilson 95% "
          "confidence intervals and the number of answers; runs that are still incomplete (free-tier quotas) show "
          "smaller n.", "", "## 1. LegalGPT vs closed-book chatbots", "",
          "See `benchmark/README.md` for the sets. Statute questions have gold answers from the statute; scenario and "
          "out-of-scope labels are silver (AI-written, awaiting legal review).", ""]
    md += ["| system | statute: right section | punishment right | punishment wrong | scenario: acceptable section | "
           "out-of-scope: answered as IPC offence | no answer (empty) |", "|---|---|---|---|---|---|---|"]
    from app.benchmark.metrics import known_sections, load_jsonl, score_oos, score_scenario, score_statute  # noqa: E402
    from app.core.corpus import load_chunks
    from app.config import get_settings
    import run_baselines as rb  # noqa: E402

    ipc = known_sections(load_chunks(get_settings().corpus_chunks_path))  # incl. state-amendment sections
    items = {it["id"]: it for it in rb.sample(7, 40, 20, 60, 30)}
    for path in sorted((BENCH / "baselines").glob("*.jsonl")):
        allans = [a for a in load_jsonl(path) if a["id"] in items and not a["answer"].startswith("ERROR")]
        ans = [a for a in allans if a["answer"].strip()]
        st = [score_statute(items[a["id"]], a["answer"], a["extra_cited"], ipc) | {"kind": items[a["id"]]["kind"]}
              for a in ans if a["set"] == "statute"]
        pun = [r for r in st if r["kind"] == "punishment"]
        sc = [score_scenario(items[a["id"]], a["answer"], a["extra_cited"], ipc) for a in ans if a["set"] == "scenario"]
        oo = [score_oos(a["answer"], a["extra_cited"]) for a in ans if a["set"] == "oos"]
        k = lambda xs, key: (sum(bool(x[key]) for x in xs), len(xs))
        md.append(f"| {path.stem} | {wilson(*k(st, 'section_correct'))} | {wilson(*k(pun, 'punishment_correct'))} | "
                  f"{wilson(*k(pun, 'punishment_wrong'))} | {wilson(*k(sc, 'hit'))} | {wilson(*k(oo, 'criminalised'))} | "
                  f"{len(allans) - len(ans)} of {len(allans)} |")
    md += ["", "## 2. Counterfactual test: LLM + rules vs LLM alone", "",
           "`benchmark/fact_patterns.jsonl`; gold verdicts computed by the rules. *Flip correct* = a one-fact change "
           "and its base case are both right; *unsafe* = a wrong CONSISTENT/INCONSISTENT verdict.", "",
           "| model | arm | n | accuracy | flip correct | omit correct | paraphrase stable | unsafe errors | cautious errors |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in cf:
        n = r["n"]
        f = lambda v, m: "-" if v is None else f"{100 * v:.0f}%"
        md.append(f"| {r['model']} | {r['arm']} | {n} | {wilson(round(r['accuracy'] * n), n)} | {f(r['flip_correct'], n)} | "
                  f"{f(r['omit_correct'], n)} | {f(r['paraphrase_stable'], n)} | {100 * r['unsafe']:.0f}% | {100 * r['cautious']:.0f}% |")
    out = REPO_ROOT / "docs" / "reports" / "benchmark_results.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    raise SystemExit(main())
